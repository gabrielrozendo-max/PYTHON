
# Lê uma medida em metros
metros = float(input("Digite uma medida em metros: "))

# 1 metro tem 100 centímetros e 1000 milímetros
centimetros = metros * 100
milimetros = metros * 1000

# Mostra os valores convertidos
print("Em centímetros:", centimetros)
print("Em milímetros:", milimetros)