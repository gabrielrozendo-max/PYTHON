
# Lê as duas notas como números reais (com casas decimais)
nota1 = float(input("Digite a primeira nota: "))
nota2 = float(input("Digite a segunda nota: "))

# Calcula a média aritmética (soma dividida por 2)
media = (nota1 + nota2) / 2

# Mostra a média com uma casa decimal usando :.1f
print("A média é: %.1f" % media)
