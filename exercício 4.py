
# Lê um número real digitado pelo usuário
numero = float(input("Digite um número: "))

# Calcula o dobro (x2), o triplo (x3) e a metade (/2)
dobro = numero * 2
triplo = numero * 3
metade = numero / 2

# Mostra os resultados
print("Dobro:", dobro)
print("Triplo:", triplo)
print("Metade:", metade)